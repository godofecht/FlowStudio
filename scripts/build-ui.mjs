import { build } from 'esbuild';
import { mkdir, writeFile, readFile, readdir } from 'node:fs/promises';
import { resolve } from 'node:path';

await mkdir('web/ui', { recursive: true });
// Monaco includes a vendored sanitizer. Use the patched, pinned package in both bundles.
const shared = { bundle: true, minify: true, target: 'es2022', legalComments: 'linked',
  plugins: [{ name: 'patched-sanitizer', setup(build) {
    build.onResolve({ filter: /dompurify\/dompurify\.js$/ }, () => ({
      path: resolve('node_modules/dompurify/dist/purify.es.mjs')
    }));
  } }] };
await build({ ...shared, entryPoints: ['frontend/main.js'], outfile: 'web/ui/workbench.js',
  format: 'esm', loader: { '.ttf': 'dataurl' },
  // Served at runtime by the native server's allowlisted static routes.
  external: ['/ide_completion_core.js'] });
await build({ ...shared,
  entryPoints: ['node_modules/monaco-editor/esm/vs/editor/editor.worker.js'],
  outfile: 'web/ui/editor.worker.js', format: 'iife' });
const notices = await Promise.all([
  ['monaco-editor', 'LICENSE'], ['lucide', 'LICENSE'], ['dompurify', 'LICENSE'],
  ['@xterm/xterm', 'LICENSE'], ['@xterm/addon-fit', 'LICENSE'], ['@xterm/addon-web-links', 'LICENSE']
].map(async ([name, file]) => `${name}\n${await readFile(`node_modules/${name}/${file}`, 'utf8')}`));
await writeFile('web/ui/THIRD_PARTY_LICENSES.txt', notices.join('\n\n'));
// The Examples view lists every executable MathFlow program in examples/.
// Each becomes a catalog entry: title from the file name, description from
// its leading comment, source verbatim.
const simulations = [];
for (const name of (await readdir('examples')).filter(n => n.endsWith('.flow')).sort()) {
  const text = await readFile(`examples/${name}`, 'utf8');
  if (!/^\s*domain\s+\w+/m.test(text)) continue;          // MathFlow programs declare a domain
  const stem = name.replace(/\.flow$/, '');
  const ns = stem.startsWith('navier_stokes');
  const family = ns ? 'Navier-Stokes' : stem.split('_')[0].replace(/^./, c => c.toUpperCase());
  const rest = (ns ? stem.slice('navier_stokes'.length) : stem.slice(stem.indexOf('_') < 0 ? stem.length : stem.indexOf('_')))
    .split('_').filter(Boolean).join(' ');
  const title = family + (rest ? ': ' + rest : '');
  const comments = [];
  for (const line of text.split('\n')) {
    if (!line.startsWith('#')) break;
    comments.push(line.replace(/^#\s?/, '').trim());
  }
  simulations.push({ id: 'mathflow-' + stem, file: name, title,
    description: comments.join(' ').slice(0, 220), text });
}
await writeFile('web/examples_mathflow.js', '/* Generated by scripts/build-ui.mjs from examples/*.flow. Do not edit. */\n' +
  'globalThis.FlowStudioMathFlowExamples = ' + JSON.stringify(simulations, null, 1) + ';\n' +
  'if (typeof module !== "undefined" && module.exports) module.exports = globalThis.FlowStudioMathFlowExamples;\n');
console.log('Built local Monaco editor, worker and workbench assets, and ' + simulations.length + ' MathFlow examples.');
