import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import { buildBrowserFlow, browserFlowToolchain } from './build-browser-flow.mjs';

// Pages ships the same workbench source as the native app.
const site = 'build/pages';
await rm(site, { recursive: true, force: true });
await mkdir(site, { recursive: true });
await cp('docs', site, { recursive: true });
await cp('docs/index.html', `${site}/guide.html`);
await cp('docs/app', `${site}/browser`, { recursive: true });
await cp('web', site, { recursive: true });
execFileSync(process.execPath, ['scripts/build-ui.mjs', '--pages'], { stdio: 'inherit' });
await buildBrowserFlow(`${site}/flow-runtime/${browserFlowToolchain}`);
const worker = await readFile('web/browser-flow-worker.js', 'utf8');
if (!worker.includes("'./flow-runtime/'")) throw new Error('Browser worker toolchain path changed');
await writeFile(`${site}/browser-flow-worker.js`, worker.replace("'./flow-runtime/'", `'./flow-runtime/${browserFlowToolchain}/'`));
// Catalogs are generated by the UI build from the checked-in examples.
for (const kind of ['mathflow', 'polyglot', 'graphics']) {
  await cp(`web/examples_${kind}.js`, `${site}/examples_${kind}.js`);
}
const revision = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
const source = await readFile('web/index.html', 'utf8');
function workbench(base) {
  return source
    .replace('<head>', `<head>\n<base href="${base}">\n<meta name="flowstudio-revision" content="${revision}">\n<script src="./browser-flow.js"></script>\n<script src="./pages-runtime.js"></script>`)
    .replace(/\b(src|href)="\/(?!\/)/g, '$1="./')
    .replace(/\b(src|href)="(\.\/[^"?]+\.(?:js|css))"/g, `$1="$2?v=${revision}"`)
    .replace('<body>', `<body><aside class="pages-notice" aria-label="Web preview"><span id="pagesRuntimeStatus" role="status">Flow runs as WebAssembly in this browser.</span><a href="./browser/">Python and R browser workspace</a><a href="./guide.html">Local runtime</a></aside>`)
    .replace('</head>', '<style>.pages-notice{height:32px;display:flex;align-items:center;gap:18px;padding:0 14px;background:#23352b;color:#d6e5db;font:12px system-ui;white-space:nowrap;overflow:auto}.pages-notice a{color:#b3d9c2}.shell{height:calc(100dvh - 32px)}</style></head>');
}
await writeFile(`${site}/index.html`, workbench('./'));
await writeFile(`${site}/app/index.html`, workbench('../'));
await writeFile(`${site}/.nojekyll`, '');
await writeFile(`${site}/revision.json`, JSON.stringify({ revision }) + '\n');
console.log(`Built Pages workbench at ${revision}`);
